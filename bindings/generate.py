"""Generate thin host declarations/resources; Zig owns every signature/schema."""
import json
from pathlib import Path
import sys

root = Path(__file__).resolve().parents[1]
contracts = {name: (root / f"packages/zig/transit-{name}/abi-v1.json").read_bytes()
             for name in ("client", "station")}
outputs = {root / f"packages/python/transit-station/transit_station/{name}-abi.json": data
           for name, data in contracts.items()}
types = {"void": "()", "uint32_t": "u32", "uint64_t": "u64", "size_t": "usize", "uint8_t": "u8"}
def rust_type(value):
    if value.endswith("*"):
        base = value[:-1].strip()
        const = base.startswith("const ")
        return ("*const " if const else "*mut ") + rust_type(base.removeprefix("const "))
    return types.get(value, value)
rust = ["// Generated by just bindings::generate; do not edit.", "#![allow(non_camel_case_types)]"]
rust.append(f'pub const MINIMUM_STACK_BYTES: usize = {json.loads(contracts["station"])["minimum_stack_bytes"]};')
for name in ("station_server", "station_growing_server", "station_buffer", "transit_client", "transit_operation", "transit_buffer"):
    rust.append(f"#[repr(C)] pub struct {name} {{ _private: [u8; 0] }}")
rust.append('unsafe extern "C" {')
for contract in contracts.values():
    for function in json.loads(contract)["functions"]:
        args = ", ".join(f"arg{i}: {rust_type(t)}" for i, t in enumerate(function["parameters"]))
        rust.append(f'    pub fn {function["name"]}({args}) -> {rust_type(function["result"])};')
rust += ["}", ""]
outputs[root / "packages/rust/transit-station/src/ffi.rs"] = "\n".join(rust).encode()
def ts(schema):
    if "anyOf" in schema or "oneOf" in schema:
        return "(" + " | ".join(ts(item) for item in schema.get("anyOf", schema.get("oneOf"))) + ")"
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    kind = schema["type"]
    if kind in ("integer", "number"):
        return "number"
    if kind in ("null", "boolean", "string"):
        return kind
    if kind == "array":
        return f"Array<{ts(schema['items'])}>"
    if kind == "object":
        return "{ " + "; ".join(f"{json.dumps(k)}{'' if k in schema.get('required', []) else '?'}: {ts(v)}" for k, v in schema.get("properties", {}).items()) + " }"
    raise ValueError(f"Unsupported host schema type {kind}")
def clean(value):
    if isinstance(value, dict):
        return {key: clean(item) for key, item in value.items() if not key.startswith("x-transit-")}
    if isinstance(value, list):
        return [clean(item) for item in value]
    return value
schemas = json.loads(contracts["station"])["schemas"]
station = json.loads(contracts["station"])
java = ["// Generated by just bindings::generate; do not edit.", "package io.transit.station;", "public final class Contract {", "    private Contract() {}",
        f'    public static final int VERSION = {station["version"]};',
        f'    public static final int MAX_STATUS = {max(station["statuses"].values())};']
for name, value in station["statuses"].items():
    java.append(f"    public static final int {name.upper()} = {value};")
java += ["}", ""]
outputs[root / "packages/java/transit-station/src/io/transit/station/Contract.java"] = "\n".join(java).encode()
outputs[root / "packages/java/transit-station/resources/station-abi.json"] = contracts["station"]
def cs_type(value, result=False):
    if value == "void": return "void"
    if value == "uint32_t": return "uint"
    if value == "uint64_t": return "ulong"
    if value == "size_t": return "nuint"
    if value.endswith("**"): return "out IntPtr"
    if value == "const uint8_t *" and not result: return "[In] byte[]"
    if value.endswith("*"): return "IntPtr"
    raise ValueError(value)
cs = ["// Generated by just bindings::generate; do not edit.", "using System.Runtime.InteropServices;", "namespace Transit.Station;", "internal static class Native {",
      f'    internal const uint Version = {station["version"]};',
      f'    internal const uint ClientVersion = {json.loads(contracts["client"])["version"]};',
      f'    internal const int MinimumStackBytes = {station["minimum_stack_bytes"]};']
for family, contract in contracts.items():
    for function in json.loads(contract)["functions"]:
        args = ", ".join(f"{cs_type(t)} arg{i}" for i, t in enumerate(function["parameters"]))
        cs.append(f'    [DllImport("transit_{family}", CallingConvention = CallingConvention.Cdecl)]')
        cs.append(f'    internal static extern {cs_type(function["result"], True)} {function["name"]}({args});')
cs += ["}", ""]
outputs[root / "packages/dotnet/transit-station/Native.cs"] = "\n".join(cs).encode()
outputs[root / "packages/dotnet/transit-station/station-abi.json"] = contracts["station"]
beam = ["%% Generated by just bindings::generate; do not edit.",
        f'-define(STATION_VERSION, {station["version"]}).',
        f'-define(STATION_MAX_STATUS, {max(station["statuses"].values())}).']
for name, value in station["statuses"].items():
    beam.append(f'-define(STATION_{name.upper()}, {value}).')
outputs[root / "packages/beam/transit-station/include/transit_station.hrl"] = ("\n".join(beam) + "\n").encode()
outputs[root / "packages/beam/transit-station/priv/station-abi.json"] = contracts["station"]
outputs[root / "packages/ts/transit-station/src/types.ts"] = (
    "// Generated by just bindings::generate; do not edit.\n" +
    "\n".join(f"export type {name} = {ts(schema)};" for name, schema in schemas.items()) + "\n").encode()
outputs[root / "packages/ts/transit-station/src/schemas.json"] = (json.dumps(clean(schemas), separators=(",", ":")) + "\n").encode()
for path, content in outputs.items():
    if "--write" in sys.argv:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
    elif not path.exists() or path.read_bytes() != content:
        raise SystemExit(f"Binding drift in {path.relative_to(root)}: run just bindings::generate")
print("Host binding declarations match shared Zig contracts.")
