"""Generate thin host declarations/resources; Zig owns every signature/schema."""
import json
import re
from pathlib import Path
import sys
from schema_types import declarations

root = Path(__file__).resolve().parents[1]
contracts = {name: (root / f"packages/zig/transit-{name}{'-bindings' if name == 'station' else ''}/abi-v1.json").read_bytes()
             for name in ("client", "station")}
outputs = {root / "sdks/python/transit-station/transit_station/station-abi.json": contracts["station"]}
outputs[root / "sdks/python/transit-client/transit_client/client-abi.json"] = contracts["client"]
# Go consumes the generated C ABI directly. Keep function-pointer signatures,
# constants and definition checks derived from the same exported Zig types.
go_contract = json.loads(contracts['client'])
go_target = root / 'sdks/go/internal/nativeclient'
outputs[go_target / 'transit_client.h'] = (root / 'packages/zig/transit-client/include/transit_client.h').read_bytes()
go_api = ['/* Generated by just bindings::generate; do not edit. */', '#pragma once',
          '#include "transit_client.h"', 'typedef struct transit_go_api {']
for function in go_contract['functions']:
    go_api.append(f'    {function["result"]} (*{function["name"]})({", ".join(function["parameters"]) or "void"});')
go_api += ['} transit_go_api;', '#define TRANSIT_GO_LOAD_API(api, image, fail) do { \\']
for function in go_contract['functions']:
    name = function['name']
    go_api.append(f'    *(void **)(&(api)->{name}) = dlsym(image, "{name}"); if (!(api)->{name}) {{ fail; }} \\')
go_api += ['} while (0)', '']
outputs[go_target / 'api_generated.h'] = '\n'.join(go_api).encode()
# Separate declarations remain gofmt-stable without Go in the generation shell.
go_constants = ['// Code generated by just bindings::generate; DO NOT EDIT.',
                'package nativeclient', '',
                f'const Definition = "{go_contract["definition"]}"',
                f'const ABIVersion = {go_contract["version"]}',
                f'const MinimumStackBytes = {go_contract["minimum_stack_bytes"]}']
for name, value in go_contract['limits'].items():
    go_constants.append(f'const {"".join(piece.title() for piece in name.split("_"))} = {value}')
for group, prefix in (('statuses', 'Status'), ('kinds', 'Kind')):
    for name, value in go_contract[group].items():
        go_constants.append(f'const {prefix}{"".join(piece.title() for piece in name.split("_"))} = {value}')
go_constants.append('')
outputs[go_target / 'constants_generated.go'] = '\n'.join(go_constants).encode()
outputs[root / 'sdks/go/serving/constants_generated.go'] = ('// Code generated by just bindings::generate; DO NOT EDIT.\npackage serving\n\n' + f'const Definition = "{go_contract["definition"]}"\nconst MaxCounter = uint64({go_contract["limits"]["max_counter"]})\n').encode()
# Public C structs are a separate ABI from the raw Zig handles. Bind every C SDK
# symbol to the same contract definition, so a foreign header/library pair fails
# at link/load time before either side can read a differently sized struct.
for family in ('client', 'station'):
    target = root / f'sdks/c/transit-{family}/include/transit'
    names = set()
    for header in target.glob('*.h'):
        if header.name.startswith('definition_'):
            continue
        source = re.sub(r'/\*.*?\*/|//[^\n]*', '', header.read_text(), flags=re.S)
        names.update(re.findall(r'^\s*(?:[A-Za-z_]\w*[ \t*]+)+(transit_[a-z0-9_]+)\s*\(', source, re.M))
    definition = json.loads(contracts[family])['definition']
    lines = ['/* Generated by just bindings::generate; do not edit. */', '#pragma once']
    lines.append(f'#define TRANSIT_SDK_{family.upper()}_DEFINITION "{definition}"')
    lines += [f'#define TRANSIT_SDK_{family.upper()}_{name.upper()} {value}'
              for name, value in json.loads(contracts[family]).get('limits', {}).items()]
    lines += [f'#define {name} {name}_{definition}' for name in sorted(names)]
    outputs[target / f'definition_{family}.h'] = ('\n'.join(lines) + '\n').encode()
# C++ decodes the same bounded catalog contracts as every other host adapter.
# These are private SDK resources, never a second hand-maintained wire schema.
catalog_schemas = json.loads(contracts['station'])['schemas']
lines = ['// Generated by just bindings::generate; do not edit.', '#pragma once',
         'namespace transit::sdk::catalog_detail::generated {']
for name in ('CatalogAction', 'CatalogResult'):
    value = json.dumps(catalog_schemas[name], separators=(',', ':'))
    lines.append(f'inline constexpr char {name}[] = R"transit({value})transit";')
lines += ['}', '']
outputs[root / 'sdks/c/transit-station/src/catalog_schema.hpp'] = '\n'.join(lines).encode()
types = {"void": "()", "uint32_t": "u32", "uint64_t": "u64", "size_t": "usize", "uint8_t": "u8"}
def rust_type(value):
    if value.endswith("*"):
        base = value[:-1].strip()
        const = base.startswith("const ")
        return ("*const " if const else "*mut ") + rust_type(base.removeprefix("const "))
    return types.get(value, value)
for family, directory in (("client", "transit-client"), ("station", "transit-station-sdk")):
    contract = json.loads(contracts[family])
    opaque = ("transit_client", "transit_operation", "transit_buffer") if family == "client" else ("station_growing_server", "station_query_client", "station_catalog_client", "station_buffer")
    dynamic = ["// Generated by just bindings::generate; do not edit.",
               "#![allow(non_camel_case_types, dead_code)]",
               f'pub const ABI_VERSION: u32 = {contract["version"]};',
               f'pub const ABI_DEFINITION: &str = "{contract["definition"]}";',
               f'pub const MINIMUM_STACK_BYTES: usize = {contract["minimum_stack_bytes"]};']
    for name, value in contract.get('limits', {}).items():
        dynamic.append(f'pub const {name.upper()}: usize = {value};')
    for name in opaque:
        dynamic.append(f'#[repr(C)] pub struct {name} {{ _private: [u8; 0] }}')
    dynamic.append('pub struct Api {')
    for function in contract['functions']:
        args = ', '.join(rust_type(t) for t in function['parameters'])
        dynamic.append(f'    pub {function["name"]}: unsafe extern "C" fn({args}) -> {rust_type(function["result"])},')
    dynamic += ['    _library: std::sync::Arc<libloading::Library>,', '}', 'impl Api {',
                '    pub unsafe fn load(library: std::sync::Arc<libloading::Library>) -> Result<Self, libloading::Error> {', '        Ok(Self {']
    for function in contract['functions']:
        name = function['name']
        dynamic.append(f'            {name}: *unsafe {{ library.get(b"{name}\\0")? }},')
    dynamic += ['            _library: library,', '        })', '    }', '}', '']
    outputs[root / f'sdks/rust/{directory}/src/abi.rs'] = '\n'.join(dynamic).encode()
    outputs[root / f'sdks/rust/{directory}/src/contract.json'] = contracts[family]
def clean(value):
    if isinstance(value, dict):
        return {key: clean(item) for key, item in value.items() if not key.startswith("x-transit-")}
    if isinstance(value, list):
        return [clean(item) for item in value]
    return value
for family in ('client', 'station'):
    directory = 'transit-client' if family == 'client' else 'transit-station-sdk'
    target = root / f'sdks/java/{directory}/resources/io/transit/sdk/{family}'
    outputs[target / 'contract.json'] = contracts[family]
    outputs[target / 'schemas.json'] = (json.dumps(clean(json.loads(contracts[family])['schemas']), separators=(',', ':')) + '\n').encode()
def cs_type(value, result=False):
    if value == "void": return "void"
    if value == "uint32_t": return "uint"
    if value == "uint64_t": return "ulong"
    if value == "size_t": return "nuint"
    if value.endswith("**"): return "out IntPtr"
    if value == "const uint8_t *" and not result: return "[In] byte[]"
    if value.endswith("*"): return "IntPtr"
    raise ValueError(value)
for family in ('client', 'station'):
    contract = json.loads(contracts[family])
    namespace = 'Transit.Client.Internal' if family == 'client' else 'Transit.Station.Sdk.Internal'
    dynamic = ['// Generated by just bindings::generate; do not edit.',
               'using System.Runtime.InteropServices;', f'namespace {namespace};',
               'internal sealed class NativeApi {',
               f'    internal const uint Version = {contract["version"]};',
               f'    internal const string Definition = "{contract["definition"]}";',
               f'    internal const int MinimumStackBytes = {contract["minimum_stack_bytes"]};']
    for function in contract['functions']:
        name = function['name']
        args = ', '.join(f'{cs_type(t)} arg{i}' for i, t in enumerate(function['parameters']))
        dynamic += ['    [UnmanagedFunctionPointer(CallingConvention.Cdecl)]',
                    f'    internal delegate {cs_type(function["result"], True)} {name}Delegate({args});',
                    f'    internal readonly {name}Delegate {name};']
    dynamic += ['    internal NativeApi(IntPtr library) {']
    for function in contract['functions']:
        name = function['name']
        dynamic.append(f'        {name} = Marshal.GetDelegateForFunctionPointer<{name}Delegate>(NativeLibrary.GetExport(library, "{name}"));')
    dynamic += ['    }', '}', '']
    directory = 'transit-client' if family == 'client' else 'transit-station-sdk'
    target = root / f'sdks/dotnet/{directory}'
    outputs[target / 'Internal/NativeApi.cs'] = '\n'.join(dynamic).encode()
    outputs[target / 'contract.json'] = contracts[family]
outputs[root / "sdks/beam/transit-client/priv/contract.json"] = contracts["client"]
outputs[root / "sdks/beam/transit-station-sdk/priv/contract.json"] = contracts["station"]
for family, directory in (("client", "transit-client"), ("station", "transit-station-sdk")):
    contract = json.loads(contracts[family])
    target = root / "sdks/ts" / directory / "src"
    outputs[target / "contract.json"] = contracts[family]
    outputs[target / "schemas.json"] = (json.dumps(clean(contract["schemas"]), separators=(",", ":")) + "\n").encode()
    outputs[target / "wire.ts"] = (
        "// Generated by just bindings::generate; do not edit.\n" +
        "\n".join(declarations(name, schema) for name, schema in contract["schemas"].items()) + "\n").encode()
for family in ('client', 'station'):
    contract = json.loads(contracts[family])
    target = root / f'sdks/ruby/transit-{family}/lib/transit/{family}'
    outputs[target / 'contract.json'] = contracts[family]
    outputs[target / 'schemas.json'] = (json.dumps(clean(contract['schemas']), separators=(",", ":")) + "\n").encode()
for path, content in outputs.items():
    if "--write" in sys.argv:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
    elif not path.exists() or path.read_bytes() != content:
        raise SystemExit(f"Binding drift in {path.relative_to(root)}: run just bindings::generate")
print("Host binding declarations match shared Zig contracts.")
