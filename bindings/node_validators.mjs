// Compile the canonical SDK schemas with the same pinned Ajv/options used by
// the runtime compiler. Keep diagnostics intact: SDK callers expose .errors.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { createHash } from "node:crypto";

// Contract checks install the client compiler only. Both packages must pin the
// same compiler before sharing this build dependency.
const require = createRequire(new URL("../sdks/ts/transit-client/package.json", import.meta.url));
const { Ajv } = require("ajv");
const standalone = require("ajv/dist/standalone").default;
const version = require("ajv/package.json").version;
for (const directory of ["transit-client", "transit-station-sdk"]) {
  const source = new URL(`../sdks/ts/${directory}/src/`, import.meta.url);
  const manifest = JSON.parse(readFileSync(new URL("../package.json", source), "utf8"));
  if (manifest.dependencies.ajv !== version)
    throw new Error(`Unpinned SDK validator compiler: ${directory}`);
  const schemas = JSON.parse(readFileSync(new URL("schemas.json", source), "utf8"));
  const ajv = new Ajv({ strict: true, code: { source: true, esm: true } });
  const names = Object.keys(schemas);
  for (const name of names) ajv.addSchema(schemas[name], name);
  const generated = standalone(ajv, Object.fromEntries(names.map((name) => [name, name])));
  const header = "// Generated by just bindings::generate; do not edit.\n";
  const runtime = generated.includes("require(")
    ? 'import { createRequire } from "node:module";\nconst require = createRequire(import.meta.url);\n'
    : "";
  const javascript = header + runtime + generated + "\n";
  const digest = createHash("sha256").update(javascript).digest("hex");
  for (const [name, text] of [
    [
      "validators.json",
      JSON.stringify({ ajv: require("ajv/package.json").version, sha256: digest }) + "\n",
    ],
    [
      "validators.d.ts",
      header +
        'import type { Validator } from "./validation.js";\n' +
        names.map((name) => `export const ${name}: Validator;`).join("\n") +
        "\n",
    ],
  ]) {
    const path = new URL(name, source);
    if (process.argv.includes("--check")) {
      if (readFileSync(path, "utf8") !== text)
        throw new Error(`SDK validator drift: ${directory}/${name}`);
    } else writeFileSync(path, text);
  }
  // Build output; the checked-in digest above binds every validation branch and
  // error detail without duplicating megabytes of generated code in Git.
  writeFileSync(new URL("validators.js", source), javascript);
}
