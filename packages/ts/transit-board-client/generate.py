"""Deterministic TS types and runtime schema from Board's generated OpenAPI."""
import json
from pathlib import Path
import sys
root = Path(__file__).resolve().parents[3]
source = json.loads((root / "contracts/transit-board-v1.openapi.json").read_text())

sys.path.insert(0, str(root / "bindings"))
from schema_types import declarations_at

def clean(s):
    # Keep runtime validation vocabulary only; extension metadata is for bindings.
    if isinstance(s, dict):
        return {k: (v.replace("#/components/schemas/", "#/$defs/") if k == "$ref" else clean(v))
                for k, v in s.items() if not k.startswith("x-transit-")}
    if isinstance(s, list):
        return [clean(v) for v in s]
    return s

outputs = {
    "types.ts": "// Generated by generate.py from the Zig-owned OpenAPI. Do not edit.\n" + declarations_at({f"#/components/schemas/{name}": (name, schema) for name, schema in source["components"]["schemas"].items()}),
    "schemas.json": json.dumps({"$id": "urn:transit:board:browser:v1", "$defs": clean(source["components"]["schemas"])}, separators=(",", ":")) + "\n",
}
for name, data in outputs.items():
    path = Path(__file__).parent / "src" / name
    if "--check" in sys.argv:
        if not path.exists() or path.read_text() != data:
            raise SystemExit(f"Board client drift: regenerate {path.relative_to(root)}")
    else:
        path.write_text(data)
