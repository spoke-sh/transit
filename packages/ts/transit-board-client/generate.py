"""Deterministic TS types and runtime schema from Board's generated OpenAPI."""
import json
from pathlib import Path
import sys
root = Path(__file__).resolve().parents[3]
source = json.loads((root / "contracts/transit-board-v1.openapi.json").read_text())

def ts(s):
    if "const" in s:
        return json.dumps(s["const"])
    if "anyOf" in s or "oneOf" in s:
        return "(" + " | ".join(ts(item) for item in s.get("anyOf", s.get("oneOf"))) + ")"
    if "enum" in s:
        return " | ".join(json.dumps(item) for item in s["enum"])
    kind = s["type"]
    if kind in ("integer", "number"):
        return "number"
    if kind == "null":
        return "null"
    if kind in ("boolean", "string"):
        return kind
    if kind == "array":
        return f"Array<{ts(s['items'])}>"
    if kind == "object":
        return "{ " + "; ".join(f"{json.dumps(k)}{'' if k in s.get('required', []) else '?'}: {ts(v)}" for k, v in s.get("properties", {}).items()) + " }"
    raise ValueError(kind)

def clean(s):
    # Keep runtime validation vocabulary only; extension metadata is for bindings.
    if isinstance(s, dict):
        return {k: clean(v) for k, v in s.items() if not k.startswith("x-transit-")}
    if isinstance(s, list):
        return [clean(v) for v in s]
    return s

outputs = {
    "types.ts": "// Generated by generate.py from the Zig-owned OpenAPI. Do not edit.\n" + "\n".join(f"export type {name} = {ts(schema)};" for name, schema in source["components"]["schemas"].items()) + "\n",
    "schemas.json": json.dumps(clean(source["components"]["schemas"]), separators=(",", ":")) + "\n",
}
for name, data in outputs.items():
    path = Path(__file__).parent / "src" / name
    if "--check" in sys.argv:
        if not path.exists() or path.read_text() != data:
            raise SystemExit(f"Board client drift: regenerate {path.relative_to(root)}")
    else:
        path.write_text(data)
