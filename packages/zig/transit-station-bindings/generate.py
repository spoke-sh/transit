"""Generate the Station ABI header and shared host schemas from Zig reflection."""
import json
from pathlib import Path
import sys

root = Path(__file__).resolve().parent
raw = sys.stdin.buffer.read()
contract = json.loads(raw)
lines = ["/* Generated by just contract::station-generate; do not edit. */",
         "#ifndef TRANSIT_STATION_H", "#define TRANSIT_STATION_H",
         "#include <stddef.h>", "#include <stdint.h>",
         '#ifdef __cplusplus\nextern "C" {\n#endif',
         f'#define STATION_ABI_VERSION {contract["version"]}u',
         f'#define STATION_ABI_DEFINITION "{contract["definition"]}"',
         f'#define STATION_MINIMUM_STACK_BYTES {contract["minimum_stack_bytes"]}u',
         "typedef struct station_growing_server station_growing_server;",
         "typedef struct station_query_client station_query_client;",
         "typedef struct station_mutation_client station_mutation_client;",
         "typedef struct station_catalog_client station_catalog_client;",
         "typedef struct station_buffer station_buffer;"]
for name, value in contract["statuses"].items():
    lines.append(f"#define STATION_STATUS_{name.upper()} {value}u")
for function in contract["functions"]:
    parameters = ", ".join(f"{value} arg{i}" for i, value in enumerate(function["parameters"])) or "void"
    lines.append(f'{function["result"]} {function["name"]}({parameters});')
lines += ["#ifdef __cplusplus\n}\n#endif", "#endif", ""]
for path, data in ((root / "include/transit_station.h", "\n".join(lines).encode()),
                   (root / "abi-v1.json", raw)):
    if "--write" in sys.argv:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    elif not path.exists() or path.read_bytes() != data:
        raise SystemExit("Station ABI/schema drift: run just contract::station-generate")
print("Station ABI and host schemas match the Zig implementation.")
