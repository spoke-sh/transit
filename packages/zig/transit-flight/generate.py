"""Derive the selected Flight wire declarations from pinned upstream protobufs."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile

from google.protobuf import descriptor_pb2 as d

root = Path(__file__).resolve().parent
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
manifest = json.loads((root / 'proto/manifest.json').read_text())
for entry in manifest['sources']:
    assert hashlib.sha256((root / 'proto' / entry['file']).read_bytes()).hexdigest() == entry['sha256'], entry['file']
with tempfile.TemporaryDirectory(prefix='transit-flight-schema-') as work:
    output = Path(work) / 'flight.pb'
    subprocess.run(['protoc', '--proto_path=' + str(root / 'proto'), '--include_imports', '--descriptor_set_out=' + str(output), str(root / 'proto/Flight.proto'), str(root / 'proto/FlightSql.proto'), 'google/protobuf/any.proto'], check=True)
    descriptor = d.FileDescriptorSet.FromString(output.read_bytes())

messages, enums = {}, {}
def visit(prefix, message):
    name = prefix + '.' + message.name
    messages[name] = message
    for child in message.nested_type:
        visit(name, child)
    for enum in message.enum_type:
        enums[name + '.' + enum.name] = enum

for file in descriptor.file:
    for message in file.message_type:
        visit('.' + file.package, message)
    for enum in file.enum_type:
        enums['.' + file.package + '.' + enum.name] = enum

selected = set()
def include(name):
    if name in selected:
        return
    selected.add(name)
    if name in messages:
        for field in messages[name].field:
            if field.type_name:
                include(field.type_name)

for name in ('FlightDescriptor', 'FlightInfo', 'FlightEndpoint', 'Ticket', 'SchemaResult', 'FlightData', 'Criteria', 'Action', 'Empty', 'ActionType'):
    include('.arrow.flight.protocol.' + name)
for name in ('CommandGetSqlInfo', 'CommandGetCatalogs', 'CommandGetDbSchemas', 'CommandGetTables', 'CommandGetTableTypes', 'CommandGetXdbcTypeInfo', 'CommandStatementQuery', 'TicketStatementQuery', 'SqlInfo'):
    include('.arrow.flight.protocol.sql.' + name)
# Well-known types come from the same locked protoc installation as Timestamp.
include('.google.protobuf.Any')

def identifier(name):
    for prefix in ('.arrow.flight.protocol.sql.', '.arrow.flight.protocol.', '.google.protobuf.'):
        if name.startswith(prefix):
            return name[len(prefix):].replace('.', '_')
    raise AssertionError(name)

scalars = {'double': 'f64', 'float': 'f32', 'int32': 'i32', 'int64': 'i64', 'uint32': 'u32', 'uint64': 'u64', 'sint32': 'i32', 'sint64': 'i64', 'fixed32': 'u32', 'fixed64': 'u64', 'sfixed32': 'i32', 'sfixed64': 'i64', 'bool': 'bool', 'string': '[]const u8', 'bytes': '[]const u8'}
lines = ['// Generated by generate.py from Apache Arrow 23.0.0; do not edit.', 'const p = @import("transit_grpc").protobuf;', '']
for name in sorted(selected):
    if name in enums:
        lines.append(f'pub const {identifier(name)} = enum(i32) {{')
        for value in enums[name].value:
            lines.append(f'    @"{value.name}" = {value.number},')
        lines += ['    _,', '};', '']
        continue
    message = messages[name]
    assert not message.options.map_entry
    lines.append(f'pub const {identifier(name)} = struct {{')
    kinds = {}
    for field in message.field:
        kind = d.FieldDescriptorProto.Type.Name(field.type)[5:].lower()
        kinds[field.name] = kind
        element = identifier(field.type_name) if field.type_name else scalars[kind]
        if field.label == d.FieldDescriptorProto.LABEL_REPEATED:
            typ, default = '[]const ' + element, '&.{}'
        elif field.proto3_optional or kind == 'message':
            typ, default = '?' + element, 'null'
        else:
            assert not field.HasField('oneof_index'), 'qualify explicit oneof selection before generation'
            typ = element
            default = '""' if kind in ('string', 'bytes') else 'false' if kind == 'bool' else '@fromBackingInt(0)' if kind == 'enum' else '0'
        lines.append(f'    @"{field.name}": {typ} = {default},')
    lines.append('    pub const pb_fields = .{')
    for field in message.field:
        packed = f', .packed_encoding = {str(field.options.packed).lower()}' if field.options.HasField('packed') else ''
        lines.append(f'        .@"{field.name}" = p.Field{{ .number = {field.number}, .kind = .@"{kinds[field.name]}"{packed} }},')
    lines += ['    };', '};', '']
formatted = subprocess.run(['zig', 'fmt', '--stdin'], input='\n'.join(lines), capture_output=True, text=True, check=True).stdout
target = root / 'src/Wire.zig'
if args.check:
    assert target.read_text() == formatted, 'Flight declarations drifted; run generate.py'
else:
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(formatted)
print('Flight wire declarations match the pinned upstream protobuf schemas.')
