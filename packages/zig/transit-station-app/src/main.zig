//! Offline compiler: no admission, publication, transport or effects on edit.
const std = @import("std");
const app = @import("transit_station_app");
pub fn main(init: std.process.Init) void {
    var diagnostic: app.Diagnostic = .{};
    run(init, &diagnostic) catch |err| {
        var buffer: [4096]u8 = undefined;
        var out = std.Io.File.stderr().writerStreaming(init.io, &buffer);
        if (diagnostic.format == .json) {
            const value = diagnostic.structured(err) catch fallback: {
                var value = app.protocol.Diagnostic.init("application.diagnostic_unavailable", .internal, .output, .not_submitted, .local_before_dispatch, "The offline compiler failed and could not retain its diagnostic detail. No application was published.") catch unreachable;
                value.cause = app.protocol.Diagnostic.Code.init(@errorName(err)) catch null;
                break :fallback value;
            };
            std.json.Stringify.value(value, .{}, &out.interface) catch {};
            out.interface.writeByte('\n') catch {};
        } else diagnostic.render(&out.interface, err) catch {};
        out.interface.flush() catch {};
        std.process.exit(1);
    };
}
fn run(init: std.process.Init, diagnostic: *app.Diagnostic) !void {
    var args = try init.minimal.args.toSlice(init.arena.allocator());
    if (args.len > 1 and std.mem.eql(u8, args[1], "--diagnostics=json")) {
        diagnostic.format = .json;
        args = args[1..];
    }
    var output: [8192]u8 = undefined;
    var stdout = std.Io.File.stdout().writerStreaming(init.io, &output);
    if (args.len == 2 and std.mem.eql(u8, args[1], "schema")) {
        diagnostic.reset(.output);
        try app.Api.schema(&stdout.interface);
    } else {
        if (args.len != 3) return error.UsageExpectedParseOrFormatAndFile;
        const parse = std.mem.eql(u8, args[1], "parse");
        const format = std.mem.eql(u8, args[1], "format");
        const module = std.mem.eql(u8, args[1], "module");
        if (!parse and !format and !module) return error.UnknownApplicationCommand;
        diagnostic.stage = .input;
        diagnostic.file = try app.protocol.Diagnostic.SourcePath.init(args[2]);
        const input = try std.Io.Dir.cwd().readFileAlloc(init.io, args[2], init.gpa, .limited(app.Model.max_program_bytes));
        defer init.gpa.free(input);
        var canonical: [app.Model.max_program_bytes]u8 = undefined;
        if (parse or module) {
            var program = try app.Sql.parseDiagnostic(init.gpa, input, diagnostic);
            defer program.deinit();
            diagnostic.reset(.validate);
            _ = try app.Api.canonical(program.definition, &canonical);
            diagnostic.reset(.output);
            if (module) try stdout.interface.writeAll("// Generated by transit-app module. A proposal, never an authority or fallback.\nimport { decodeDefinition } from '@rey/transit-application';\nexport const proposal = decodeDefinition(");
            var encoder: std.json.Stringify = .{ .writer = &stdout.interface, .options = .{ .whitespace = .indent_2 } };
            try app.protocol.Json.write(program.definition, &encoder);
            if (module) try stdout.interface.writeAll(");");
            try stdout.interface.writeByte('\n');
        } else {
            diagnostic.stage = .parse;
            const program = app.protocol.Json.parseFromSlice(app.Model.Definition, init.gpa, input) catch |err| {
                jsonPosition(init.gpa, input, diagnostic);
                return err;
            };
            defer program.deinit();
            try program.value.validateDiagnostic(diagnostic);
            diagnostic.reset(.validate);
            const bytes = try app.Api.canonical(program.value, &canonical);
            diagnostic.reset(.output);
            try stdout.interface.writeAll(bytes);
        }
    }
    try stdout.interface.flush();
}
fn jsonPosition(allocator: std.mem.Allocator, input: []const u8, diagnostic: *app.Diagnostic) void {
    // Revisit only the original local bytes on failure. A structural/semantic
    // rejection of valid JSON has no invented scanner coordinate.
    var scanner = std.json.Scanner.initCompleteInput(allocator, input);
    defer scanner.deinit();
    var location: std.json.Scanner.Diagnostics = .{};
    scanner.enableDiagnostics(&location);
    const parsed = std.json.parseFromTokenSource(std.json.Value, allocator, &scanner, .{}) catch |err| {
        if (err == error.OutOfMemory) return;
        diagnostic.offset = location.getByteOffset();
        diagnostic.locate(input);
        return;
    };
    parsed.deinit();
}
