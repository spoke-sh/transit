"""Check the committed application schema against the actual public Zig exporter."""
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
actual = json.loads(subprocess.check_output([sys.argv[1], 'schema']))
expected = json.loads((ROOT / 'packages/zig/transit-station-app/api/application.schema.json').read_text())
assert actual == expected, 'application public schema drift'
program = ROOT/'packages/zig/transit-station-app/src/fixtures/board.sql'
definition = json.loads(subprocess.check_output([sys.argv[1], 'parse', str(program)]))
module = subprocess.check_output([sys.argv[1], 'module', str(program)], text=True)
prefix = "// Generated by transit-app module. A proposal, never an authority or fallback.\nimport { decodeDefinition } from '@transit/application';\nexport const proposal = decodeDefinition("
assert module.startswith(prefix) and module.endswith(');\n')
assert json.loads(module[len(prefix):-3]) == definition, 'generated module changed declaration semantics'
print('Application schema matches the owning Zig types.')
